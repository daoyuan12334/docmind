-- -----------------------------
-- DocMind 核心库表结构（H2 / PostgreSQL 共通方言）
-- 约定：JSON 字段统一用 TEXT 存储，由 Java 层序列化，保证跨库一致。
-- -----------------------------

CREATE TABLE IF NOT EXISTS sys_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    role          VARCHAR(32)  NOT NULL DEFAULT 'MEMBER',
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS kb_knowledge_base (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(128) NOT NULL,
    description     VARCHAR(512),
    owner_id        BIGINT       NOT NULL,
    visibility      VARCHAR(16)  NOT NULL DEFAULT 'PRIVATE',
    embedding_model VARCHAR(64)  NOT NULL DEFAULT 'text-embedding-v4',
    chunk_size      INT          NOT NULL DEFAULT 800,
    chunk_overlap   INT          NOT NULL DEFAULT 120,
    top_k           INT          NOT NULL DEFAULT 6,
    doc_count       INT          NOT NULL DEFAULT 0,
    chunk_count     INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS kb_document (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id       BIGINT       NOT NULL,
    name        VARCHAR(255) NOT NULL,
    ext         VARCHAR(16)  NOT NULL,
    mime_type   VARCHAR(128),
    size_bytes  BIGINT       NOT NULL DEFAULT 0,
    checksum    VARCHAR(64)  NOT NULL,
    storage_key VARCHAR(512) NOT NULL,
    status      VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    stage       VARCHAR(32),
    progress    INT          NOT NULL DEFAULT 0,
    error_msg   VARCHAR(1024),
    page_count  INT          DEFAULT 0,
    chunk_count INT          DEFAULT 0,
    token_count INT          DEFAULT 0,
    modality    VARCHAR(24)  DEFAULT 'TEXT',
    summary     TEXT,
    meta        TEXT,
    uploaded_by BIGINT,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_doc_kb ON kb_document(kb_id, deleted);
CREATE INDEX IF NOT EXISTS idx_doc_status ON kb_document(status);

CREATE TABLE IF NOT EXISTS kb_chunk (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id        BIGINT  NOT NULL,
    doc_id       BIGINT  NOT NULL,
    chunk_index  INT     NOT NULL,
    content      TEXT    NOT NULL,
    content_hash VARCHAR(64),
    token_count  INT     DEFAULT 0,
    page_no      INT,
    content_type VARCHAR(16) DEFAULT 'TEXT',
    meta         TEXT,
    vector_id    VARCHAR(64),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chunk_doc ON kb_chunk(doc_id);
CREATE INDEX IF NOT EXISTS idx_chunk_kb ON kb_chunk(kb_id);

CREATE TABLE IF NOT EXISTS ingest_task (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id     BIGINT  NOT NULL,
    kb_id      BIGINT  NOT NULL,
    trace_id   VARCHAR(64),
    status     VARCHAR(16) NOT NULL,
    stage      VARCHAR(32),
    attempt    INT     NOT NULL DEFAULT 1,
    error      VARCHAR(2000),
    cost_ms    BIGINT,
    started_at   TIMESTAMP,
    finished_at  TIMESTAMP,
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ingest_doc ON ingest_task(doc_id, id);

CREATE TABLE IF NOT EXISTS chat_conversation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id         BIGINT,
    user_id       BIGINT NOT NULL,
    title         VARCHAR(128),
    message_count INT    DEFAULT 0,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted       BOOLEAN   NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_conv_user ON chat_conversation(user_id, deleted);

CREATE TABLE IF NOT EXISTS chat_message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT NOT NULL,
    role             VARCHAR(16) NOT NULL,
    content          TEXT,
    citations        TEXT,
    attachments      TEXT,
    prompt_tokens    INT DEFAULT 0,
    completion_tokens INT DEFAULT 0,
    latency_ms       INT DEFAULT 0,
    model            VARCHAR(64),
    trace_id         VARCHAR(64),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_msg_conv ON chat_message(conversation_id, id);

CREATE TABLE IF NOT EXISTS ai_usage (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT,
    kb_id             BIGINT,
    conversation_id   BIGINT,
    scene             VARCHAR(32),
    model             VARCHAR(64),
    prompt_tokens     INT DEFAULT 0,
    completion_tokens INT DEFAULT 0,
    latency_ms        INT DEFAULT 0,
    success           BOOLEAN DEFAULT TRUE,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_usage_time ON ai_usage(created_at);
CREATE INDEX IF NOT EXISTS idx_usage_user ON ai_usage(user_id, created_at);

CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT,
    username   VARCHAR(64),
    action     VARCHAR(64),
    resource   VARCHAR(128),
    detail     TEXT,
    ip         VARCHAR(64),
    ua         VARCHAR(255),
    trace_id   VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_time ON audit_log(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_log(user_id, created_at);
